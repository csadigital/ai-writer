#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const { createInterface } = require('node:readline/promises');
const { Writable } = require('node:stream');
const root = path.resolve(__dirname, '..');

function buildConfig(input = {}) {
    const config = {
        NODE_ENV: input.NODE_ENV || 'development', PORT: input.PORT || '3000',
        SESSION_SECRET: input.SESSION_SECRET?.length >= 32 ? input.SESSION_SECRET : crypto.randomBytes(32).toString('hex'),
        TRUST_PROXY: input.TRUST_PROXY || '0', OPENAI_API_KEY: input.OPENAI_API_KEY || '',
        OPENAI_MODEL: input.OPENAI_MODEL || 'gpt-4.1-mini',
        DB_HOST: input.DB_HOST || '127.0.0.1', DB_PORT: input.DB_PORT || '3306',
        DB_USER: input.DB_USER || 'ai_writer', DB_PASSWORD: input.DB_PASSWORD || crypto.randomBytes(24).toString('base64url'),
        DB_NAME: input.DB_NAME || 'ai_writer',
        MYSQL_ROOT_PASSWORD: input.MYSQL_ROOT_PASSWORD || crypto.randomBytes(32).toString('base64url')
    };
    if (!/^[A-Za-z0-9_]{1,64}$/.test(config.DB_NAME)) throw new Error('Database name must use 1–64 letters, digits or underscores.');
    if (!/^[A-Za-z0-9_]{1,32}$/.test(config.DB_USER)) throw new Error('Database username must use 1–32 letters, digits or underscores.');
    for (const key of ['DB_PORT', 'PORT']) if (!/^\d+$/.test(String(config[key])) || Number(config[key]) < 1 || Number(config[key]) > 65535) throw new Error(`${key} must be a valid port.`);
    return config;
}
function serializeConfig(config) {
    return '# Generated by npm run setup. Never commit this file.\n' + Object.entries(config).map(([key, value]) => {
        value = String(value);
        if (/[\r\n]/.test(value)) throw new Error(`${key} must not contain line breaks.`);
        const quote = !value.includes("'") ? "'" : !value.includes('"') && !value.includes('\\') ? '"' : null;
        if (!quote) throw new Error(`${key} cannot be safely written to .env; avoid combining both quote types or quotes with backslashes.`);
        return `${key}=${quote}${value}${quote}`;
    }).join('\n') + '\n';
}
function run(command, args, extraEnv = {}) {
    const result = spawnSync(command, args, { cwd: root, stdio: 'inherit', env: { ...process.env, ...extraEnv }, shell: false });
    if (result.error || result.status !== 0) throw new Error(`${command} failed. Check the output above and run setup again.`);
}
async function provisionDatabase(connection, mysql, config, accountHost) {
    if (!accountHost || /[\r\n\0]/.test(accountHost)) throw new Error('Enter a valid MySQL account host.');
    await connection.query(`CREATE DATABASE IF NOT EXISTS ${mysql.escapeId(config.DB_NAME)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
    await connection.query('CREATE USER IF NOT EXISTS ?@? IDENTIFIED BY ?', [config.DB_USER, accountHost, config.DB_PASSWORD]);
    await connection.query(`GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, INDEX ON ${mysql.escapeId(config.DB_NAME)}.* TO ?@?`, [config.DB_USER, accountHost]);
}
async function setup() {
    const [major, minor] = process.versions.node.split('.').map(Number);
    if (major < 22 || (major === 22 && minor < 12)) throw new Error('Install Node.js 22.12 or later from https://nodejs.org and run npm run setup again.');
    if (!process.stdin.isTTY) throw new Error('Run npm run setup in an interactive terminal. Secrets are entered privately and are not printed.');
    process.chdir(root);
    console.log('\nAI Writer · Automatic setup\n');
    console.log('Installing locked dependencies and Puppeteer Chrome…');
    if (!process.env.npm_execpath) throw new Error('Run this installer using npm run setup.');
    run(process.execPath, [process.env.npm_execpath, 'ci'], { PUPPETEER_SKIP_DOWNLOAD: 'false' });
    const dotenv = require('dotenv');
    const mysql = require('mysql2/promise');
    const envPath = path.join(root, '.env');
    const previous = fs.existsSync(envPath) ? dotenv.parse(fs.readFileSync(envPath)) : {};
    let muted = false;
    const output = new Writable({ write(chunk, encoding, callback) { if (!muted) process.stdout.write(chunk); callback(); } });
    const rl = createInterface({ input: process.stdin, output, terminal: true });
    async function ask(label, fallback = '', secret = false) {
        const prompt = `${label}${fallback && !secret ? ` [${fallback}]` : secret && fallback ? ' [Enter to keep saved value]' : ''}: `;
        let answer;
        if (secret) {
            process.stdout.write(prompt); muted = true;
            try { answer = await rl.question(''); } finally { muted = false; process.stdout.write('\n'); }
        } else answer = await rl.question(prompt);
        return answer.trim() || fallback;
    }
    let config;
    try {
        const dockerAvailable = spawnSync('docker', ['compose', 'version'], { stdio: 'ignore' }).status === 0;
        const mode = await ask('MySQL setup: docker (automatic server) or existing', dockerAvailable ? 'docker' : 'existing');
        if (!['docker', 'existing'].includes(mode)) throw new Error('Choose docker or existing.');
        if (mode === 'docker' && !dockerAvailable) throw new Error('Install and start Docker with Compose support, then rerun setup.');
        const input = { ...previous };
        input.OPENAI_API_KEY = await ask('OpenAI API key (hidden)', previous.OPENAI_API_KEY || '', true);
        if (!input.OPENAI_API_KEY) throw new Error('An OpenAI API key is required. Create one in your OpenAI account, then rerun setup.');
        input.DB_NAME = await ask('Application database', previous.DB_NAME || 'ai_writer');
        input.DB_USER = await ask('Application database user', previous.DB_USER || 'ai_writer');
        if (mode === 'docker') {
            input.DB_HOST = '127.0.0.1';
            input.DB_PORT = await ask('Local MySQL port', previous.DB_PORT || '3307');
            config = buildConfig(input);
        } else {
            input.DB_HOST = await ask('MySQL host', previous.DB_HOST || '127.0.0.1');
            input.DB_PORT = await ask('MySQL port', previous.DB_PORT || '3306');
            const provision = (await ask('Create database and app user with an administrator? y/n', previous.DB_USER ? 'n' : 'y')).toLowerCase();
            if (!['y', 'n'].includes(provision)) throw new Error('Choose y or n.');
            input.DB_PASSWORD = await ask('Application DB password (hidden; empty generates one)', previous.DB_PASSWORD || '', true);
            config = buildConfig(input);
            if (provision === 'y') {
                const adminUser = await ask('MySQL administrator', 'root');
                const adminPassword = await ask('MySQL administrator password (hidden)', '', true);
                const accountHost = await ask('MySQL app account host (where the app connects from)', 'localhost');
                const connection = await mysql.createConnection({ host: config.DB_HOST, port: Number(config.DB_PORT), user: adminUser, password: adminPassword, connectTimeout: 10000 });
                try { await provisionDatabase(connection, mysql, config, accountHost); } finally { await connection.end(); }
            }
        }
        // Back up an existing local configuration. Both names are ignored by Git.
        if (fs.existsSync(envPath)) { fs.copyFileSync(envPath, `${envPath}.backup`); fs.chmodSync(`${envPath}.backup`, 0o600); }
        const serialized = serializeConfig(config);
        fs.writeFileSync(envPath, serialized, { mode: 0o600 });
        fs.chmodSync(envPath, 0o600);
        if (mode === 'docker') run('docker', ['compose', '-f', 'compose.mysql.yml', 'up', '-d', '--wait']);
        const connection = await mysql.createConnection({ host: config.DB_HOST, port: Number(config.DB_PORT), user: config.DB_USER, password: config.DB_PASSWORD, database: config.DB_NAME, connectTimeout: 10000 });
        try {
            const schema = fs.readFileSync(path.join(root, 'schema.sql'), 'utf8');
            // schema.sql contains one table statement. Strip SQL comments before execution.
            await connection.query(schema.replace(/^--.*$/gm, '').trim());
        } finally { await connection.end(); }
        console.log('\nSetup complete. Configuration saved privately to .env.\nRun npm start, then open http://localhost:' + config.PORT + '\n');
        const ffmpeg = spawnSync('ffmpeg', ['-version'], { stdio: 'ignore' });
        if (ffmpeg.status !== 0) console.log('Optional video feature: install FFmpeg and FFprobe for your operating system.');
    } finally { rl.close(); }
}
if (require.main === module) setup().catch(error => {
    // Database errors may include connection details; never print credential-bearing objects.
    const known = ['ER_ACCESS_DENIED_ERROR', 'ER_DBACCESS_DENIED_ERROR', 'ECONNREFUSED', 'ENOTFOUND'];
    console.error(known.includes(error.code) ? `Setup failed (${error.code}). Check the MySQL host, user, password and permissions; then rerun setup.` : `Setup failed: ${error.code || error.message}`);
    process.exitCode = 1;
});
module.exports = { buildConfig, serializeConfig, provisionDatabase };
